const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const crypto = require('node:crypto');
const { once } = require('node:events');
const { spawn } = require('node:child_process');
const { chromium } = require('playwright');
const sharp = require('sharp');

test('checkout wajib bukti, retry setelah reload dapat pilih bukti ulang, popup pesanan responsif', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bagus-browser-'));
  const password = crypto.randomBytes(20).toString('hex');
  const socket = net.createServer().listen(0, '127.0.0.1'); await once(socket, 'listening');
  const port = socket.address().port; await new Promise(resolve => socket.close(resolve));
  const base = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, ['server/index.js'], { cwd: path.resolve(__dirname, '..'), env: { ...process.env, PORT: String(port), DATA_DIR: dir, SESSION_SECRET: crypto.randomBytes(48).toString('hex'), ADMIN_USERNAME: 'browseradmin', ADMIN_PASSWORD: password, COOKIE_SECURE: 'false' }, stdio: ['ignore', 'pipe', 'pipe'] });
  let browser;
  t.after(async () => { await browser?.close(); if (child.exitCode === null) { const exit = once(child, 'exit'); child.kill(); await exit; } fs.rmSync(dir, { recursive: true, force: true }); });
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Server tidak siap')), 15000); child.stdout.on('data', data => { if (String(data).includes('berjalan')) { clearTimeout(timer); resolve(); } }); child.once('exit', code => { clearTimeout(timer); reject(new Error(`Server berhenti ${code}`)); }); });
  const installedChrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  browser = await chromium.launch({ headless: true, ...(fs.existsSync(installedChrome) ? { executablePath: installedChrome } : {}) });
  const context = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  const adminContext = await browser.newContext();
  const adminLogin = await adminContext.request.post(base + '/api/auth/login', { data: { username: 'browseradmin', password } }); assert.equal(adminLogin.status(), 200);
  await adminContext.request.patch(base + '/api/admin/inventory/1', { data: { quantity: 10 } });
  await adminContext.request.patch(base + '/api/admin/inventory/2', { data: { quantity: 10 } });
  const adminPage = await adminContext.newPage();
  const adminErrors = [], adminRequests = [];
  adminPage.on('pageerror', error => adminErrors.push(error.message));
  adminPage.on('request', request => { if (request.url().includes('/api/admin/products')) adminRequests.push([request.method(), request.url()]); });
  adminPage.on('console', message => { if (message.type() === 'error') adminErrors.push(message.text()); });
  adminPage.on('requestfailed', request => { if (request.url().includes('/api/admin/products')) adminErrors.push(`${request.url()} ${request.failure()?.errorText}`); });
  adminPage.on('response', response => { if (response.status() === 404) adminErrors.push(`404 ${response.url()}`); });
  await adminPage.goto(base + '/admin');
  await adminPage.waitForSelector('#adminDashboard [data-edit-product="1"]');
  await adminPage.click('[data-edit-product="1"]');
  const productPhoto = await sharp({ create: { width: 80, height: 60, channels: 3, background: '#6b8f50' } }).png().toBuffer();
  await adminPage.setInputFiles('#productImage', { name: 'produk.png', mimeType: 'image/png', buffer: productPhoto });
  await adminPage.waitForFunction(() => document.querySelector('#productImagePreview')?.src.startsWith('blob:'));
  assert.equal(await adminPage.locator('#productForm').evaluate(form => new FormData(form).get('image') instanceof File), true);
  const formState = await adminPage.locator('#productForm').evaluate(form => ({ validity: form.checkValidity(), disabled: form.querySelector('#saveProduct').disabled, file: form.elements.image?.files?.[0]?.name, id: form.elements.id?.value, price: form.elements.price?.value, name: form.elements.name?.value, category: form.elements.category?.value }));
  if (!formState.validity) throw new Error(`form invalid before save: ${JSON.stringify(formState)}`);
  const updateResponse = adminPage.waitForResponse(response => response.url().includes('/api/admin/products/1') && response.request().method() === 'PATCH', { timeout: 10000 });
  await adminPage.locator('#saveProduct').click();
  let updateResult;
  try { updateResult = await updateResponse; }
  catch (error) { throw new Error(`${error.message}; form=${JSON.stringify(formState)}; requests=${JSON.stringify(adminRequests)}; errors=${JSON.stringify(adminErrors)}`); }
  const updatePayload = await updateResult.json();
  assert.equal(updateResult.status(), 200, JSON.stringify(updatePayload));
  assert.match(updatePayload.product.image, /^\/assets\/uploads\/products\/[a-f0-9]{48}\.webp$/);
  await adminPage.waitForFunction(() => document.querySelector('#productDialog')?.open === false);
  const editedProduct = (await (await adminContext.request.get(base + '/api/admin/products')).json()).products.find(product => product.id === 1);
  assert.equal(editedProduct.image, updatePayload.product.image);
  const productImage = await adminContext.request.get(base + editedProduct.image);
  assert.equal(productImage.status(), 200);
  assert.deepEqual(adminErrors.filter(item => item.startsWith('404 ')), []);
  await adminPage.close();
  const customerContext = await browser.newContext();
  const registered = await customerContext.request.post(base + '/api/auth/register', { data: { fullName: 'Penyewa Browser', username: 'browsercustomer', password } }); assert.equal(registered.status(), 201);
  const page = await customerContext.newPage();
  const errors = [], remoteImages = [], failedRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('requestfailed', req => failedRequests.push(`${req.url()} ${req.failure()?.errorText}`));
  page.on('response', response => { if (response.status() >= 400) failedRequests.push(`${response.status()} ${response.url()}`); });
  page.on('request', req => { if (req.resourceType() === 'image' && req.url().startsWith('http') && !req.url().startsWith(base)) remoteImages.push(req.url()); });
  await page.addInitScript(() => { window.open = () => null; });
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('[data-add="1"]')?.disabled === false);
  assert.equal(await page.locator('[data-open-admin]').count(), 0, 'tautan admin tidak ditampilkan di navigasi publik');
  assert.match(await page.locator('#accountButton').getAttribute('aria-label'), /profil|masuk/i);
  const menuPage = await context.newPage();
  await menuPage.goto(base);
  await menuPage.click('#accountButton');
  await menuPage.waitForSelector('#profileMenu:not([hidden])');
  assert.deepEqual(await menuPage.locator('#profileMenu [data-profile-action]').evaluateAll(nodes => nodes.map(node => node.dataset.profileAction)), ['login', 'register']);
  await menuPage.click('#profileMenu [data-profile-action="login"]');
  await menuPage.waitForSelector('#authOverlay:not([hidden])');
  await menuPage.click('[data-close-auth]');
  await menuPage.click('#accountButton');
  await menuPage.click('#profileMenu [data-profile-action="register"]');
  await menuPage.waitForSelector('#authOverlay:not([hidden])');
  assert.equal(await menuPage.locator('#authForm #fullNameField').isHidden(), false);
  await menuPage.close();
  await page.click('[data-add="1"]'); await page.click('#cartOpen');
  await page.waitForSelector('#checkoutSubmit:not([disabled])');
  assert.equal(await page.locator('#checkoutForm [name="paymentProof"]').count(), 1);
  assert.equal(await page.locator('#checkoutForm [name="paymentProof"]').getAttribute('required'), '');
  assert.deepEqual(await page.locator('#paymentOptions input').evaluateAll(nodes => nodes.map(node => node.value)), ['SeaBank', 'GoPay']);
  await page.fill('#checkoutForm [name="fullName"]', 'Penyewa Browser');
  await page.fill('#checkoutForm [name="phone"]', '081234567890');
  await page.click('#checkoutSubmit');
  assert.equal(await page.locator('#invoiceOverlay').isVisible(), false);
  assert.equal((await (await customerContext.request.get(base + '/api/my/orders')).json()).orders.length, 0);
  const image = await sharp({ create: { width: 100, height: 160, channels: 3, background: '#d6e2d6' } }).png().toBuffer();
  await page.setInputFiles('#checkoutForm [name="paymentProof"]', { name: 'bukti.png', mimeType: 'image/png', buffer: image });
  await page.evaluate(() => { sessionStorage.setItem('bagus-checkout-request-v1', JSON.stringify({ key: 'a'.repeat(64), payload: JSON.stringify({ fullName: 'Penyewa Browser', phone: '081234567890', rentalDays: 1, paymentMethod: 'GoPay', items: [{ id: 1, quantity: 1 }] }) })); });
  await page.reload();
  await page.click('#cartOpen'); await page.waitForSelector('#checkoutRetry:not([hidden])');
  assert.equal(await page.locator('#retryCheckoutRequest').isDisabled(), true);
  await page.locator('#checkoutForm [name="paymentProof"]').evaluate(node => { node.disabled = false; });
  await page.setInputFiles('#checkoutForm [name="paymentProof"]', { name: 'bukti.png', mimeType: 'image/png', buffer: image });
  assert.equal(await page.locator('#retryCheckoutRequest').isDisabled(), false);
  await page.check('#paymentOptions input[value="GoPay"]');
  await page.click('#retryCheckoutRequest');
  await page.waitForSelector('#invoiceOverlay:not([hidden])');
  assert.match(await page.locator('#invoiceDialog').textContent(), /Menunggu verifikasi/i);
  assert.equal(await page.locator('#invoiceDialog [data-payment-proof]').count(), 1);
  assert.match(await page.locator('#invoiceDialog').textContent(), /GoPay/);
  await page.click('[data-close-invoice]');
  await page.click('[data-open-orders]'); await page.waitForSelector('#ordersOverlay:not([hidden]) [data-owned-invoice]');
  assert.equal(await page.locator('#ordersPanel').getAttribute('role'), 'dialog');
  assert.equal(await page.evaluate(() => document.body.classList.contains('no-scroll')), true);
  await page.click('[data-owned-invoice]'); await page.waitForSelector('#invoiceOverlay:not([hidden])');
  await page.click('[data-back-orders]'); await page.waitForSelector('#ordersOverlay:not([hidden])');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#ordersOverlay').isVisible(), false);
  assert.equal(await page.locator('[data-open-orders]').evaluate(node => node === document.activeElement), true);
  for (const width of [390, 768, 1280]) {
    await page.setViewportSize({ width, height: 844 });
    if (width < 761) await page.click('#menuToggle');
    await page.click('[data-open-orders]'); await page.waitForSelector('#ordersOverlay:not([hidden]) [data-owned-invoice]');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow halaman pada ${width}px`);
    assert.equal(await page.locator('#ordersPanel').evaluate(node => node.scrollWidth <= node.clientWidth), true, `overflow popup pada ${width}px`);
    await page.keyboard.press('Escape');
  }
  assert.deepEqual(remoteImages, []);
  assert.deepEqual(errors, []);
  assert.deepEqual(failedRequests, []);
});
