const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const os = require('node:os');
const net = require('node:net');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const sharp = require('sharp');

test('admin product image edit persists selected photo from dialog to catalog', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'bagus-admin-edit-'));
  const password = crypto.randomBytes(24).toString('hex');
  const env = { ...process.env, DATA_DIR: directory, SESSION_SECRET: crypto.randomBytes(48).toString('hex'), ADMIN_USERNAME: 'photo-admin', ADMIN_PASSWORD: password, COOKIE_SECURE: 'false' };
  const socket = net.createServer(); socket.listen(0, '127.0.0.1'); await once(socket, 'listening');
  const port = socket.address().port; await new Promise(resolve => socket.close(resolve));
  const base = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, ['server/index.js'], { cwd: path.resolve(__dirname, '..'), env: { ...env, PORT: String(port) }, stdio: ['ignore', 'pipe', 'pipe'] });
  let browser;
  t.after(async () => { await browser?.close(); if (child.exitCode === null) { const done = once(child, 'exit'); child.kill(); await done; } fs.rmSync(directory, { recursive: true, force: true }); });
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Server tidak siap')), 15000);
    child.stdout.on('data', chunk => { if (String(chunk).includes('berjalan')) { clearTimeout(timeout); resolve(); } });
    child.once('exit', code => { clearTimeout(timeout); reject(new Error(`Server berhenti: ${code}`)); });
  });
  browser = await chromium.launch({ headless: true, ...(fs.existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe') ? { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' } : {}) });
  const context = await browser.newContext();
  const login = await context.request.post(base + '/api/auth/login', { data: { username: 'photo-admin', password } });
  assert.equal(login.status(), 200);
  await context.request.patch(base + '/api/admin/inventory/1', { data: { quantity: 5 } });
  const page = await context.newPage();
  const pageErrors = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  page.on('request', request => { if (request.url().includes('/api/admin/products')) pageErrors.push(`REQUEST ${request.method()} ${request.url()}`); });
  page.on('console', message => { if (message.type() === 'error') pageErrors.push(`CONSOLE ${message.text()}`); });
  page.on('requestfailed', request => { if (request.url().includes('/api/admin/products')) pageErrors.push(`FAILED ${request.url()} ${request.failure()?.errorText}`); });
  await page.goto(base + '/admin');
  await page.waitForSelector('#adminDashboard [data-edit-product="1"]');
  await page.click('[data-edit-product="1"]');
  const png = await sharp({ create: { width: 70, height: 50, channels: 3, background: '#62814a' } }).png().toBuffer();
  await page.setInputFiles('#productImage', { name: 'produk.png', mimeType: 'image/png', buffer: png });
  const preview = page.locator('#productImagePreview');
  const beforeSrc = await preview.getAttribute('src');
  await page.setInputFiles('#productImage', { name: 'produk.png', mimeType: 'image/png', buffer: png });
  await page.waitForFunction(previous => document.querySelector('#productImagePreview')?.src !== previous && document.querySelector('#productImagePreview')?.src.startsWith('blob:'), beforeSrc);
  await page.locator('#saveProduct').waitFor({ state: 'visible' });
  const formState = await page.locator('#productForm').evaluate(form => ({imageCount: form.elements.image?.files?.length, fileName: form.elements.image?.files?.[0]?.name, reset: form.elements.resetImage?.value, validity: form.checkValidity(), saveDisabled: form.querySelector('#saveProduct')?.disabled}));
  assert.equal(formState.imageCount, 1, JSON.stringify(formState));
  assert.equal(formState.reset, 'false', JSON.stringify(formState));
  assert.equal(formState.validity, true, JSON.stringify(formState));
  assert.ok(await page.locator('#saveProduct').isVisible());
  const responsePromise = page.waitForResponse(result => result.url().includes('/api/admin/products/1') && result.request().method() === 'PATCH', { timeout: 10000 });
  await page.locator('#saveProduct').click();
  const response = await responsePromise;
  const result = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(result));
  assert.match(result.product.image, /^\/assets\/uploads\/products\/[a-f0-9]{48}\.webp$/);
  await page.waitForFunction(() => document.querySelector('#productDialog')?.open === false);
  const publicProduct = (await (await context.request.get(base + '/api/products')).json()).products.find(product => product.id === 1);
  assert.equal(publicProduct.image, result.product.image);
  const imageResponse = await context.request.get(base + publicProduct.image);
  assert.equal(imageResponse.status(), 200);
  assert.equal(await page.locator('#adminNotice').textContent(), 'Perubahan barang berhasil disimpan.');
  assert.match(imageResponse.headers()['content-type'], /^image\/webp/);
  assert.equal((await sharp(Buffer.from(await imageResponse.body())).metadata()).format, 'webp');
  assert.ok(pageErrors.includes(`CONSOLE Failed to load resource: the server responded with a status of 404 (Not Found)`));
});
